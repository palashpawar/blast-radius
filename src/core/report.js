// Render an analysis result for its two audiences: a compact JSON payload for
// Rovo/MCP tool calls, and an Atlassian Document Format comment for the issue.

const LEVEL_EMOJI = { low: '🟢', medium: '🟡', high: '🟠', critical: '🔴' };

/** Trimmed result for LLM tool calls: what the agent needs, nothing it doesn't. */
export function forAgent(r) {
  return {
    issueKey: r.issueKey,
    source: r.source,
    score: r.score,
    level: r.level,
    headline: r.headline,
    factors: r.factors.map(({ label, points, detail }) => ({ label, points, detail })),
    touches: {
      services: r.surface.services,
      components: r.surface.components,
      repositories: r.code.repositories.map((x) => x.name),
      pullRequests: r.code.pullRequests.map((x) => ({ name: x.name, url: x.url, status: x.status })),
    },
    incidents: r.incidents.slice(0, 5).map((i) => ({
      key: i.key, summary: i.summary, severity: i.severity, ageDays: i.ageDays, open: i.open, matches: i.matches,
    })),
    dependents: r.dependents.map((d) => ({ key: d.key, relation: d.relation, open: d.open })),
    concurrent: r.concurrent.map((c) => ({ key: c.key, summary: c.summary })),
    atRiskParents: r.parents.filter((p) => p.reasons.length).map((p) => ({ key: p.key, summary: p.summary, reasons: p.reasons })),
    notify: r.notify.slice(0, 6).map((p) => ({ name: p.displayName, accountId: p.accountId, reasons: p.reasons })),
    warnings: r.warnings,
  };
}

const text = (t, marks) => ({ type: 'text', text: t, ...(marks ? { marks } : {}) });
const strong = (t) => text(t, [{ type: 'strong' }]);
const para = (...content) => ({ type: 'paragraph', content });
const heading = (t) => ({ type: 'heading', attrs: { level: 4 }, content: [text(t)] });
const bullets = (items) => ({
  type: 'bulletList',
  content: items.map((content) => ({ type: 'listItem', content: [para(...content)] })),
});
const mention = (p) => ({ type: 'mention', attrs: { id: p.accountId, text: `@${p.displayName}` } });

export function toAdf(r) {
  const content = [
    para(strong(`${LEVEL_EMOJI[r.level]} Blast radius: ${r.level.toUpperCase()} (${r.score}/100)`)),
    para(text(r.headline)),
  ];

  if (r.factors.length) {
    content.push(heading('Why'));
    content.push(bullets(r.factors.map((f) => [strong(`+${f.points} ${f.label}`), ...(f.detail ? [text(`: ${f.detail}`)] : [])])));
  }
  if (r.incidents.length) {
    content.push(heading('What broke here before'));
    content.push(bullets(r.incidents.slice(0, 3).map((i) => [
      strong(i.key), text(` ${i.summary} (${i.severity}, ${i.ageDays}d ago${i.open ? ', still open' : ''}). Matches ${i.matches.join(', ')}.`),
    ])));
  }
  if (r.notify.length) {
    content.push(heading('Loop in'));
    content.push(bullets(r.notify.slice(0, 5).map((p) => [mention(p), text(` — ${p.reasons.join('; ')}`)])));
  }
  content.push(para(text(`Generated by Blast Radius from ${r.source === 'teamwork-graph' ? 'Teamwork Graph + Jira' : 'Jira'} data.`, [{ type: 'em' }])));

  return { type: 'doc', version: 1, content };
}
